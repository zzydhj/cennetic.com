-- ============================================================================
-- 0005 · 摘掉 articles.lastmod 的库级默认值（它会让整条发布链路停摆）
-- 现象：
--   后台点「发布」后 Action 在「从 Supabase 生成内容快照」一步中止，报
--   「articles.lastmod 存的是「2026-10-30 02:44:48.302802+00」，不是原文日期」，
--   并提示去重跑 0002 —— 而 0002 其实早就跑过了，照提示做也解决不了。
-- 根因（逐列实测出来的，不是猜的）：
--   这列早期是 timestamptz，0002 把列型改成 text 时 Postgres 把原默认值 cast 后保留了，
--   于是变成 `default now()::text`，写入形态自带时区偏移与小数秒。
--   快照的形状守卫 assertDateText() 见到 + / Z / 小数秒必须整体中止（它该这么严：
--   否则会把上百个内容文件的日期全部改写并上线），所以一行脏数据 = 全站发布停摆。
--   同表的 modified（可空、无默认）与 date（not null、无默认）都干净，只有这一列有问题。
-- 谁会踩到：
--   后台表单不踩（新建时 defaults() 给文本框填 ''，显式覆盖 default）；
--   踩到的是「省略该列的写入」——Supabase 表格编辑器手工加行、CSV 导入、脚本直插 REST。
-- 为什么是 set default '' 而不是 drop default：
--   这列是 not null，drop default 后省略该列会直接 400（像 date 那样明确报错，也算好）；
--   但后台一直在传 ''，把默认值统一成 '' 让「省略」与「后台保存」得到同一个干净结果，
--   快照侧 opt() 会把 '' 当作未设置，不写 lastmod 字段，产物字节不受影响。
-- 执行：Supabase SQL Editor 整份运行。可重复执行。
-- 影响：只改列默认值，不动任何存量数据（实测全库 113 行 lastmod 均为原文格式，脏行 0）。
-- ============================================================================

alter table public.articles alter column lastmod set default '';
