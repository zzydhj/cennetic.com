-- ============================================================================
-- 0003 · 产品表补 faq 列
-- 原因：
--   文章/页面早已有 faq jsonb（[{q,a}] → 前台问答区 + FAQPage 结构化数据），
--   产品缺失：后台没地方填、产品页不渲染、Google 结果也不出问答下拉。
--   本迁移把产品对齐到同一套链路。
-- 执行：Supabase SQL Editor 整份运行。可重复执行（if not exists + 默认 '[]'，
--   存量行不受影响）；快照侧 faqOf() 对空数组返回 undefined，空值不会改动产物字节。
-- 顺序：先跑本 SQL，再部署带产品 faq 字段的后台，否则产品保存会因缺列报错。
-- ============================================================================

alter table public.products
  add column if not exists faq jsonb not null default '[]'::jsonb;
